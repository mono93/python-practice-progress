# Integer

variable_a = 20
variable_b = 10

total = variable_a + variable_b
print(f"Total: {total}")

remainder = variable_a - variable_b
print(f"Remainder: {remainder}")

count = 5
person_count = variable_a // count
print(f"Person count: {person_count}")


leftover = variable_a % (count + 1)
print(f"Leftover: {leftover}")

checker_1 = 10 / 3
checker_2 = 47 // 10
checker_3 = 47 % 10
print(f"Checker 1: {checker_1}")
print(f"Checker 2: {checker_2}")
print(f"Checker 3: {checker_3}")

checker_4 = 10 ** 3
print(f"Checker 4: {checker_4}")

checker_5 = 1_000_000_000
print(f"Checker 5: {checker_5}")
